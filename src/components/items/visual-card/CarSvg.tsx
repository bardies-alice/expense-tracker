function zoneStatus(zoneStatuses: Record<string, ComponentStatus>, ...keys: string[]) {
  for (const key of keys) {
    if (zoneStatuses[key]) return zoneStatuses[key];
  }
  return "unknown" as ComponentStatus;
}

